        'Step "The embedded browser window (WebView2 + .NET SDK)"',
        "if (-not (Get-Command dotnet -ErrorAction SilentlyContinue)) {",
        '  Warn "No .NET SDK, so the WebView2 window host cannot be built on this machine."',
