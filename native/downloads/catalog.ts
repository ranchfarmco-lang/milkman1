/** §33 — the download-all package, with the tree the specification names. */
export function downloadAll(): { buffer: Buffer; files: { path: string; bytes: number; sha256: string }[] } {
  const entries: ZipEntry[] = [];
  const manifest: { path: string; bytes: number; sha256: string }[] = [];

  const add = (path: string, data: string | Uint8Array) => {
    const bytes = typeof data === "string" ? new TextEncoder().encode(data) : data;
    entries.push({ path: `SUGAR/${path}`, data: bytes });
    manifest.push({ path, bytes: bytes.byteLength, sha256: sha256(bytes) });
  };

  add("README.md", bundleReadme());

  // The host itself, so the download is the program.
  for (const file of sourceFiles()) {
    add(`Source/${file.path}`, file.bytes);
  }

  for (const installer of installerEntries()) add(installer.path, installer.text);

  // §32 — Android, Chromebook and the mobile web/PWA instructions.
  add(
    "Android/README.md",
    [
      "# SUGAR on Android",
      "",
      "A phone does not need the host application. Open the remote portal address in",
      "Chrome and sign in — that is the whole Android story, and it is real (§3, §19).",
      "",
      "If you want the host's own HTTP server running on the phone itself, Termux can",
      "do that: `bash Android/install-termux.sh`. What Termux cannot give you is the",
      "embedded browser window, because Android has no system webview a shell can",
      "embed — the phone's browser is the browser. The host says so rather than",
      "pretending (§51, §52).",
      "",
    ].join("\n"),
  );

  add(
    "Chromebook/README.md",
    [
      "# SUGAR on a Chromebook",
      "",
      "Turn on the Linux container (Settings → About ChromeOS → Developers → Linux",
      "development environment → Turn on), then:",
      "",
      "```",
      "bash Chromebook/install-chromebook.sh",
      "bun run host.ts",
      "```",
      "",
      "The container can run the host — it has a real Linux environment with a real",
      "WebKitGTK. Any other device on the same network reaches it at the LAN address",
      "the host prints.",
      "",
    ].join("\n"),
  );

  add(
    "Documentation/README.md",
    [
      "# SUGAR documentation",
      "",
      "The host serves its own documentation at `/` — the dashboard links to every",
      "section §49 lists: getting started, installation, first start, connecting to",
      "the Internet, using Starlink, using Proton VPN, remote access, phone",
      "connection, Android, iPhone, Chromebook, Windows, Linux, Mac, troubleshooting,",
      "security, downloads, updates, uninstallation and advanced settings.",
      "",
      "Two things worth reading before anything else:",
      "",
      "- `REMOTE-ACCESS.md` — why a Starlink connection needs the relay, and how to",
      "  run one.",
      "- `SECURITY.md` — what the portal can and cannot reach on this computer (§65).",
      "",
    ].join("\n"),
  );

  add(
    "Documentation/REMOTE-ACCESS.md",
    [
      "# Remote access",
      "",
      "The host tests whether the Internet can reach it directly (§11). On Starlink it",
      "usually cannot: the connection is behind carrier-grade NAT, which is normal and",
      "not a fault. Proton VPN does not change that, because it does not forward ports.",
      "",
      "So the host holds one encrypted outbound connection to a relay (§14). A remote",
      "browser talks to the relay; the relay writes down that connection; the host",
      "answers. Nothing ever connects inward.",
      "",
      "Run a relay anywhere with a public address — a small VPS, a container, a",
      "machine with a real port. This archive includes the relay:",
      "",
      "```",
      "bun run relay.ts --port 8443 --secret \"$(openssl rand -hex 24)\"",
      "```",
      "",
      "Then set that address in the host's settings, or with:",
      "",
      "```",
      "SUGAR_RELAY=https://relay.example bun run host.ts",
      "```",
      "",
      "The public address the relay assigns is the address the dashboard shows. It is",
      "never fabricated: if the tunnel is not connected, the dashboard says there is",
      "no public address (§16, §51).",
      "",
    ].join("\n"),
  );

  add(
    "Documentation/SECURITY.md",
    [
      "# Security",
      "",
      "What the remote portal can reach on this computer:",
      "",
      "- the host's own HTTP server, on one port that the host chose;",
      "- the dashboard, the diagnostics, the download centre and the browser area.",
      "",
      "What it cannot reach (§65):",
      "",
      "- the operating system's own administrative interfaces;",
      "- SSH, file shares, remote desktop, or any other service;",
      "- any operating-system command: there is no route from a request to a shell.",
      "",
      "Authentication (§17): the portal requires a password; sessions are random",
      "tokens in `HttpOnly` cookies; five failed attempts lock a client out with a",
      "delay that grows; every state-changing request needs a CSRF token.",
      "",
      "Credentials: passwords are stored only as scrypt hashes, in the operating",
      "system's own credential store where one exists (§46).",
      "",
    ].join("\n"),
  );

  add(
    "Configuration/README.md",
    [
      "# Configuration examples",
      "",
      "The host writes its settings beside itself, one file per section (§46):",
      "",
      "- `user.json` — beginner or advanced mode, the tunnel provider.",
      "- `network.json` — the preferred port, whether to listen on the LAN.",
      "- `server.json` — the port that was actually chosen.",
      "- `security.json` — session length, lockout policy.",
      "- `state.json` — whether the first-run wizard has finished.",
      "- `devices.json` — paired devices, as hashes. Never a secret.",
      "",
      "No password, session token or private key appears in any of them, and the host",
      "refuses to write a field that looks like one.",
      "",
    ].join("\n"),
  );

  add(
    "Configuration/network.example.json",
    JSON.stringify({ preferredPort: 8123, allowLan: true, monitorSeconds: 15 }, null, 2) + "\n",
  );
  add(
    "Configuration/security.example.json",
    JSON.stringify(
      { requireAuth: true, sessionMinutes: 720, maxAttempts: 5, lockoutMinutes: 15, httpsOnlyRemote: true },
      null,
      2,
    ) + "\n",
  );

  // §35 — the checksums file, which is what makes the rest verifiable.
  const checksumLines = manifest
    .map((file) => `${file.sha256}  ${file.path}`)
    .join("\n");
  add("Checksums/SHA256SUMS.txt", `${checksumLines}\n`);
  add(
    "Checksums/README.md",
    [
      "# Checksums",
      "",
      `Every file in this archive, with its SHA-256, for build ${RELEASE.build}.`,
      "",
      "Verify from the top of the unpacked archive:",
      "",
      "```",
      "sha256sum -c Checksums/SHA256SUMS.txt      # Linux",
      "shasum -a 256 -c Checksums/SHA256SUMS.txt  # macOS",
      "```",
      "",
      "The checksums file covers the archive's own contents. The archive's own SHA-256",
      "is shown on the download card in the host's download centre, computed over the",
      "exact bytes you received (§35).",
      "",
    ].join("\n"),
  );

  return { buffer: zipBytes(entries), files: manifest };
}

