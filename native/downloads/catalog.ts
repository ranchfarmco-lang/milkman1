/**
 * §31–§35, §66, §67 — the download centre.
 *
 * The specification's rule here is the one that shapes this whole file: no
 * fake buttons. So every entry below is one of exactly three honest things:
 *
 *   GENERATED — a real archive or installer the host builds on demand from
 *   files that exist, and whose SHA-256 the host can compute because it holds
 *   the bytes.
 *
 *   SERVED — a real file sitting on this machine, served with its real size and
 *   checksum.
 *
 *   EXTERNAL — a component that cannot legally or technically be bundled
 *   (WebView2, .NET, a tunnel provider account). These are listed with their
 *   official source and never mirrored (§34, §67).
 *
 * §33's "DOWNLOAD ALL" is real: it assembles the tree the specification names —
 * SUGAR/Windows, Linux, macOS, Android, Chromebook, Documentation,
 * Configuration, Checksums — with real installer scripts in each folder.
 */

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { RELEASE, versionLine } from "../core/version.ts";
import { readableSize, sha256, zipBytes, type ZipEntry } from "./zip.ts";

/** The native host's own source directory, found from this file's location. */
export function nativeRoot(): string {
  return dirname(dirname(fileURLToPath(import.meta.url)));
}

const SKIP_DIRS = new Set(["node_modules", ".git", "downloads", "browser-profile", "credentials", "logs"]);

/** Every real source file of the host, so the bundle is the actual program. */
export function sourceFiles(root = nativeRoot()): { path: string; bytes: Uint8Array }[] {
  const found: { path: string; bytes: Uint8Array }[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith(".")) continue;
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name)) continue;
        walk(full);
      } else if (entry.isFile()) {
        found.push({ path: relative(root, full).replace(/\\/g, "/"), bytes: readFileSync(full) });
      }
    }
  };
  if (existsSync(root)) walk(root);
  return found;
}

