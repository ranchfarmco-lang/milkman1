/**
 * §26, §61 — the installer, in the platform's own language.
 *
 * Because this build is source, the installer's job is truthful and small: it
 * checks for the one runtime the host needs, unpacks the source beside itself,
 * builds the desktop window host where that platform supports one, and puts a
 * launcher on the PATH. It installs no compiler the user did not already have,
 * and it says which component it is on as it goes, which is §61's progress.
 */
